async def seed_tomato_knowledge(db: AsyncSession, sync_vector: bool = True) -> int:
    """初始化预装入番茄精品农业知识库，支持增量注入与元数据全量回填"""
    count = 0
    updated_count = 0
    for seed in TOMATO_KNOWLEDGE_SEED:
        existing = await knowledge_service.check_duplicate(db, seed["question"])
        if not existing:
            await knowledge_service.create_knowledge(
                db=db,
                question=seed["question"],
                answer=seed["answer"],
                keywords=seed["keywords"],
                category=seed["category"],
                crop=seed.get("crop"),
                region=seed.get("region"),
                growth_stage=seed.get("growth_stage"),
                topic=seed.get("topic"),
                disease=seed.get("disease"),
                source_type=seed.get("source_type", "standard"),
                source_name=seed.get("source_name"),
                authority_level=seed.get("authority_level", "L1"),
                version=seed.get("version", "v1.0"),
                publish_date=seed.get("publish_date"),
                url=seed.get("url"),
                source_updated_at=seed.get("source_updated_at"),
                effective_from=seed.get("effective_from"),
                effective_to=seed.get("effective_to"),
                sync_vector=sync_vector
            )
            count += 1
        # Existing rows belong to their editor; seeding never rewrites reviewed data.
    logger.info(f"成功预装载 {count} 条、元数据回填升级 {updated_count} 条番茄专业植保知识")
    return count
